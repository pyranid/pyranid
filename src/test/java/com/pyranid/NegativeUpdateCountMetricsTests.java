package com.pyranid;

import org.hsqldb.jdbc.JDBCDataSource;
import org.junit.jupiter.api.Test;

import javax.sql.DataSource;
import java.lang.reflect.InvocationTargetException;
import java.lang.reflect.Method;
import java.lang.reflect.Proxy;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.util.ArrayList;
import java.util.List;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.*;

class NegativeUpdateCountMetricsTests {
	@Test
	void negativeCountsRemainPublicDriverResultsWhileMetricsReportUnknown() {
		for (long count : new long[]{-1L, -2L, 0L, 7L}) {
			Fixture fixture = new Fixture(count);
			TransactionOutcome<Void> outcome = fixture.database.transactionWithOutcome(() -> {
				assertEquals(count, fixture.database.query("INSERT INTO work (value) VALUES (11)").execute());
				assertTrue(fixture.database.query("INSERT INTO work (value) VALUES (12)")
						.executeReturningGeneratedKey(Long.class).isPresent());
				assertEquals(1, fixture.database.query("INSERT INTO work (value) VALUES (13)")
						.executeReturningGeneratedKeys(Long.class).size());
			});
			assertEquals(TransactionResult.COMMITTED, outcome.getResult());
			assertTrue(outcome.getFailure().isEmpty());
			assertEquals(List.of(11, 12, 13), fixture.inspection.query("SELECT value FROM work ORDER BY value").fetchList(Integer.class));
			assertEquals(3, fixture.results.size());
			Long expectedAffected = count < 0L ? null : count;
			assertEquals(new StatementResult(null, expectedAffected), fixture.results.get(0));
			assertEquals(new StatementResult(1L, expectedAffected), fixture.results.get(1));
			assertEquals(new StatementResult(1L, expectedAffected), fixture.results.get(2));
		}
	}

	private static final class Fixture {
		final Database database;
		final Database inspection;
		final List<StatementResult> results = new ArrayList<>();

		Fixture(long driverCount) {
			JDBCDataSource source = new JDBCDataSource();
			source.setUrl("jdbc:hsqldb:mem:negative_metrics_" + UUID.randomUUID());
			source.setUser("sa");
			source.setPassword("");
			this.inspection = Database.with(source, DatabaseType.GENERIC).build();
			this.inspection.query("CREATE TABLE work (id BIGINT GENERATED BY DEFAULT AS IDENTITY, value INT)").execute();
			DataSource wrapped = proxy(DataSource.class, (method, args) -> {
				Object result = invoke(source, method, args);
				if (!(result instanceof Connection connection)) return result;
				return proxy(Connection.class, (jdbc, parameters) -> {
					Object value = invoke(connection, jdbc, parameters);
					if (!(value instanceof PreparedStatement statement)) return value;
					return proxy(PreparedStatement.class, (call, values) -> {
						Object answer = invoke(statement, call, values);
						if (call.getName().equals("executeLargeUpdate")) return driverCount;
						if (call.getName().equals("executeUpdate")) return (int) driverCount;
						return answer;
					});
				});
			});
			this.database = Database.with(wrapped, DatabaseType.GENERIC).metricsCollector(new MetricsCollector() {
				@Override public void didExecuteStatement(StatementContext<?> context, StatementLog<?> log, StatementResult result) {
					results.add(result);
				}
			}).build();
		}
	}

	@FunctionalInterface private interface Call { Object run(Method method, Object[] args) throws Throwable; }
	private static <T> T proxy(Class<T> type, Call call) {
		return type.cast(Proxy.newProxyInstance(type.getClassLoader(), new Class<?>[]{type},
				(proxy, method, args) -> call.run(method, args)));
	}
	private static Object invoke(Object target, Method method, Object[] args) throws Throwable {
		try { return method.invoke(target, args); }
		catch (InvocationTargetException failure) { throw failure.getCause(); }
	}
}
